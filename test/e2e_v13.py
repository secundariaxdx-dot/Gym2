import subprocess, sys, time, os
from playwright.sync_api import sync_playwright
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
srv = subprocess.Popen([sys.executable, '-m', 'http.server', '8768', '-d', ROOT], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
time.sleep(1)
OUT = os.path.join(ROOT, 'shots'); fails, errors = [], []
def check(c, m):
    print(('OK   ' if c else 'FAIL ') + m)
    if not c: fails.append(m)
try:
    with sync_playwright() as p:
        b = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
        ctx = b.new_context(viewport={'width': 375, 'height': 812}, device_scale_factor=2, is_mobile=True, has_touch=True, color_scheme='dark')
        pg = ctx.new_page()
        pg.on('pageerror', lambda e: errors.append(str(e)))
        pg.on('console', lambda m: errors.append(m.text) if m.type == 'error' else None)
        # datos de la v1.2 sin routineOrder
        pg.goto('http://localhost:8768/'); pg.wait_for_selector('.routine')
        pg.evaluate("() => { const s = JSON.parse(localStorage.getItem('gymapp.v1')); delete s.routineOrder; localStorage.setItem('gymapp.v1', JSON.stringify(s)); }")
        pg.reload(); pg.wait_for_selector('.routine')
        check([x.split('\n')[0] for x in pg.locator('.routine h2').all_inner_texts()] == ['Push', 'Pull', 'Piernas'], 'Migra el orden de rutinas')

        # --- Biblioteca y filtros en Ejercicios
        pg.click('[data-t=ej]'); pg.wait_for_selector('#ex-list')
        check(pg.locator('#ex-list .item.mine').count() == 17, 'Mis 17 ejercicios')
        nlib = pg.locator('#ex-list .item.lib').count()
        check(nlib == 122 - 17, 'Biblioteca sin duplicar los míos: %d' % nlib)
        pg.click('[data-a=flt][data-k=m][data-v="Cuádriceps"]')
        names = pg.locator('#ex-list .item .ex-name').all_inner_texts()
        check(len(names) > 5 and any('Prensa' in n for n in names), 'Filtro por músculo: %d' % len(names))
        pg.click('[data-a=flt][data-k=e][data-v=barra]')
        names = pg.locator('#ex-list .item .ex-name').all_inner_texts()
        check(all('barra' in n.lower() for n in names) and len(names) >= 2, 'Filtro músculo + equipo: ' + str(names))
        pg.click('[data-a=flt][data-k=e][data-v=barra]'); pg.click('[data-a=flt][data-k=m][data-v="Cuádriceps"]')
        pg.fill('#q', 'press inclinado')
        check(pg.locator('#ex-list .item').count() >= 3, 'Búsqueda sin acentos y por palabras')
        pg.fill('#q', 'hack')
        pg.screenshot(path=OUT + '/30-biblioteca.png')
        pg.click('#ex-list .item.lib'); pg.wait_for_selector('#f-name')
        check(pg.input_value('#f-name') == 'Sentadilla hack (máquina)' and pg.input_value('#f-muscle') == 'Cuádriceps', 'Biblioteca abre el ejercicio preconfigurado')
        pg.click('[data-a=exedit-save]')
        check(pg.locator('#ex-list .item.mine').count() == 1 and pg.locator('#ex-list .item.lib').count() == 0, 'Pasa a mis ejercicios')
        pg.fill('#q', '')

        # --- Rutinas: crear, renombrar, añadir desde biblioteca, duplicar, ordenar, borrar
        pg.click('[data-a=new-routine]'); pg.wait_for_selector('#f-rname')
        pg.fill('#f-rname', 'Full body')
        pg.click('[data-a=r-add]'); pg.wait_for_selector('#pick-list')
        pg.click('#modal [data-a=flt][data-k=m][data-v=Pecho]'); pg.click('#modal [data-a=flt][data-k=e][data-v=barra]')
        check(pg.locator('#pick-list .item.lib').count() >= 3, 'Selector con filtros muestra biblioteca')
        pg.screenshot(path=OUT + '/31-selector.png')
        pg.fill('#pq', 'banca inclinado'); pg.click('#pick-list .item >> nth=0')
        pg.wait_for_selector('#f-rname')
        check(pg.locator('#modal .li').count() == 1, 'Ejercicio de biblioteca añadido a la rutina')
        check(pg.evaluate("!!window.__gym.state.exercises.find(e => e.id === 'press-banca-inc')"), 'Y adoptado en mis ejercicios')
        pg.click('[data-a=r-dup]'); pg.wait_for_selector('#f-rname')
        check(pg.input_value('#f-rname') == 'Full body (copia)', 'Duplicar rutina')
        pg.click('[data-a=r-del]'); pg.click('[data-a=confirm-yes]')
        st = pg.evaluate('window.__gym.state')
        check(len(st['routines']) == 4 and len(st['routineOrder']) == 4, 'Borrar la copia deja 4 rutinas')
        rows = pg.locator('#app .li-main .ex-name').all_inner_texts()
        check(rows == ['Push', 'Pull', 'Piernas', 'Full body'], 'Orden: ' + str(rows))
        pg.click('[data-a=ro-up] >> nth=3'); pg.click('[data-a=ro-up] >> nth=2')
        rows = pg.locator('#app .li-main .ex-name').all_inner_texts()
        check(rows[1] == 'Full body', 'Reordenar rutinas: ' + str(rows))
        pg.screenshot(path=OUT + '/32-rutinas.png')
        pg.click('[data-t=hoy]'); pg.wait_for_selector('.routine')
        hoy = [x.split('\n')[0] for x in pg.locator('.routine h2').all_inner_texts()]
        check(hoy == ['Push', 'Full body', 'Pull', 'Piernas'], 'Hoy respeta el orden: ' + str(hoy))
        # renombrar Push y comprobar en Hoy
        pg.click('.routine >> nth=0 >> [data-a=edit-routine]'); pg.fill('#f-rname', 'Push A'); pg.click('#modal [data-a=close]')
        check(pg.locator('.routine h2').first.inner_text() == 'Push A', 'Renombrar rutina')
        # entrenar la nueva rutina y cambiar un ejercicio por otro de la biblioteca
        pg.click('.routine >> nth=1 >> [data-a=start]'); pg.wait_for_selector('section.ex.open')
        check('Sin historial' in pg.locator('section.ex.open .hint').first.inner_text(), 'Ejercicio nuevo sin historial')
        pg.click('[data-a=swap]'); pg.wait_for_selector('#pick-list')
        check(pg.locator('#modal [data-a=flt][data-v=Pecho].on').count() == 1, 'Cambiar ejercicio filtra por su músculo')
        pg.click('#pick-list .item.lib >> nth=0')
        check(pg.locator('section.ex').count() == 1, 'Ejercicio cambiado')
        pg.click('[data-a=discard]'); pg.click('[data-a=confirm-yes]')
        # sesión libre con ejercicio de peso corporal
        pg.click('[data-a=start][data-k=free]'); pg.click('[data-a=add-ex]'); pg.fill('#pq', 'dominadas')
        pg.click('#pick-list .item >> nth=0')
        pg.fill('section.ex.open input[data-f=r][data-j="0"]', '8'); pg.fill('section.ex.open input[data-f=w][data-j="0"]', '')
        pg.click('section.ex.open .chk >> nth=0')
        check(pg.locator('section.ex.open .set.done').count() == 1, 'Serie de peso corporal sin peso se puede marcar')
        pg.click('[data-a=finish]'); pg.click('[data-a=finish-yes]'); pg.wait_for_selector('#modal h2'); pg.click('#modal [data-a=close]')
        pg.click('[data-a=start][data-k=free]'); pg.click('[data-a=add-ex]'); pg.fill('#pq', 'dominadas'); pg.click('#pick-list .item >> nth=0')
        tg = pg.locator('section.ex.open .set:not(.head) .tgt').first.inner_text()
        check(tg == 'reps 9', 'Dominadas: objetivo +1 repetición sin peso (' + tg + ')')
        b.close()
finally:
    srv.terminate()
print('Errores:', errors or 'ninguno'); print('FALLOS:', fails or 'ninguno')
sys.exit(1 if fails or errors else 0)
